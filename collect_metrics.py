"""Optional read-only Docker-to-node-exporter textfile adapter; no autoheal."""

import argparse
import json
import os
import subprocess
import tempfile
import time
from pathlib import Path


def command(args):
    return subprocess.check_output(args, text=True, stderr=subprocess.DEVNULL, timeout=8)


def collect(project):
    values = {}
    for component in ("bluez", "relay"):
        try:
            raw = command(
                ["docker", "inspect", "--format", "{{json .State}}", f"{project}-{component}-1"]
            )
            state = json.loads(raw)
            values[f'component_up{{component="{component}"}}'] = int(
                state.get("Running") is True and state.get("Health", {}).get("Status") == "healthy"
            )
        except (OSError, ValueError, subprocess.SubprocessError):
            values[f'component_up{{component="{component}"}}'] = 0
    try:
        status = json.loads(
            command(["docker", "exec", f"{project}-relay-1", "cat", "/run/siri-remote/status.json"])
        )
    except (OSError, ValueError, subprocess.SubprocessError):
        status = {}
    values["heartbeat_fresh"] = int(0 <= time.monotonic() - status.get("heartbeat", -999) < 15)
    for key in ["backend_ready", "bond_present", "remote_connected"]:
        values[key] = int(status.get(key) is True)
    values["repair_required"] = int(status.get("phase") == "repair_required")
    values["http_failures_total"] = int(status.get("http_failures", 0))
    values["http_successes_total"] = int(status.get("http_successes", 0))
    return values


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", default="siri-remote-bridge")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--maintenance-file", type=Path)
    args = parser.parse_args()
    values = collect(args.project)
    values["collector_timestamp_seconds"] = int(time.time())
    values["maintenance"] = int(bool(args.maintenance_file and args.maintenance_file.exists()))
    text = "# Generated by siri-remote-bridge; no secrets or raw input.\n"
    for suffix, value in sorted(values.items()):
        text += f"siri_remote_bridge_{suffix} {value}\n"
    fd, name = tempfile.mkstemp(prefix=".siri-remote-", dir=args.output.parent)
    try:
        with os.fdopen(fd, "w") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(name, 0o644)
        os.replace(name, args.output)
    finally:
        if os.path.exists(name):
            os.unlink(name)


if __name__ == "__main__":
    main()
